// Лабораторная работа №1. Вариант 7.
// Задание: найти натуральное наименьшее решение уравнения
//          a^2 + b^2 = c^2 + d^2,  где a != b и c != d.
//
// КАК РАБОТАЕТ АЛГОРИТМ (простыми словами):
//  Шаг 1. Перебираем сумму s = 5, 6, 7, ... (наименьшая сумма двух разных
//         квадратов это 1^2 + 2^2 = 5). Так как суммы проверяются по
//         возрастанию, ПЕРВАЯ найденная сумма и есть наименьшее решение.
//  Шаг 2. Для текущей s ищем ВСЕ пары (x, y), у которых x^2 + y^2 = s.
//         Перебираем x = 1, 2, 3..., вычисляем y = sqrt(s - x^2) и
//         проверяем, что y целый и y > x (тогда автоматически x != y,
//         и каждая пара учитывается один раз).
//  Шаг 3. Если для суммы s нашлось две РАЗНЫЕ пары - решение найдено:
//         первая пара это (a, b), вторая это (c, d).
//
// КАК ЭТО ОФОРМЛЕНО (модульность):
//   Program.Main           - общий порядок работы (ввод -> решение -> вывод);
//   PrintDescription       - описание программы для пользователя;
//   ReadLimit              - ввод границы с проверкой корректности;
//   FindSmallestSolution   - сам поиск наименьшего решения;
//   PairsWithSquareSum     - поиск всех пар (x, y) для одной суммы;
//   IsValid                - самопроверка найденного решения;
//   PrintSolution          - вывод результата.
//   Каждый метод решает одну задачу, поэтому его можно менять и
//   тестировать независимо от остальных (сопровождаемость, модульность).
//
// Реализованные примитивы качества:
//   завершенность        - программа полностью решает задачу варианта;
//   точность             - арифметика целочисленная, повторная проверка
//                          x*x + y*y == s исключает погрешность Sqrt;
//   автономность         - только стандартная библиотека .NET;
//   устойчивость         - некорректный ввод (не число) не приводит к сбою;
//   защищенность         - отбрасываются значения вне допустимого диапазона,
//                          обработано закрытие потока ввода (Ctrl+D/Ctrl+Z);
//   п-документированность/с-документированность - XML-описание каждого
//                          метода, шапка с описанием алгоритма и ограничений;
//   информативность      - программа объясняет свое назначение при запуске;
//   коммуникабельность   - понятные подсказки при вводе и сообщения об ошибках;
//   понятность/удобочитаемость - говорящие имена методов и переменных;
//   модульность/сопровождаемость - логика разнесена по отдельным методам,
//                          изменение одного метода не затрагивает остальные;
//   расширяемость        - способ поиска пар вынесен в PairsWithSquareSum,
//                          его можно заменить более эффективным алгоритмом,
//                          не трогая остальной код;
//   временная эффективность/эффективность по ресурсам - суммы проверяются
//                          по возрастанию (решение находится почти сразу),
//                          хранится только маленький список пар.
//
// Критерии качества: функциональность и надежность (обязательные) +
//   легкость применения, эффективность, сопровождаемость.
// ============================================================================
namespace Lab1;

/// <summary>
/// Лабораторная работа №1, вариант 7.
/// Поиск наименьшего натурального решения уравнения
/// a^2 + b^2 = c^2 + d^2 (a != b, c != d).
/// </summary>
public static class Program
{
    /// <summary>Нижняя граница поиска: 1^2 + 2^2 = 5.</summary>
    private const int MinSum = 5;

    /// <summary>Верхняя допустимая граница суммы (ограничение перебора).</summary>
    private const int MaxSum = 10000;

    /// <summary>Точка входа: описание, ввод границы, поиск и вывод решения.</summary>
    public static void Main()
    {
        PrintDescription();

        int? limit = ReadLimit();      // null - пользователь прервал ввод
        if (limit == null)
            return;

        var solution = FindSmallestSolution(limit.Value);

        if (solution == null)
            Console.WriteLine($"Решение при s от {MinSum} до {limit} не найдено.");
        else
            PrintSolution(solution.Value);
    }

    /// <summary>Печатает назначение программы (информативность).</summary>
    private static void PrintDescription()
    {
        Console.WriteLine("Программа ищет наименьшее натуральное решение " +
                          "уравнения a^2 + b^2 = c^2 + d^2 (a != b, c != d).");
    }

    /// <summary>
    /// Запрашивает верхнюю границу суммы, пока ввод не станет корректным
    /// (устойчивость, защищенность, коммуникабельность).
    /// </summary>
    /// <returns>Корректная граница или null, если поток ввода закрыт.</returns>
    private static int? ReadLimit()
    {
        while (true)
        {
            Console.Write($"Введите верхнюю границу суммы s " +
                          $"(целое число от {MinSum} до {MaxSum}): ");
            string input = Console.ReadLine();

            if (input == null)                        // Ctrl+D / Ctrl+Z
            {
                Console.WriteLine();
                Console.WriteLine("Ввод прерван. Программа завершена.");
                return null;
            }

            if (!int.TryParse(input, out int limit))  // не число - не падаем
            {
                Console.WriteLine("Ошибка: нужно целое число. Повторите ввод.");
                continue;
            }

            if (limit < MinSum || limit > MaxSum)     // вне диапазона
            {
                Console.WriteLine($"Ошибка: число должно быть " +
                                  $"от {MinSum} до {MaxSum}. Повторите ввод.");
                continue;
            }

            return limit;
        }
    }

    /// <summary>
    /// Ищет наименьшее решение: перебирает суммы s по возрастанию
    /// и возвращает первую, представимую двумя разными парами квадратов.
    /// </summary>
    /// <returns>Кортеж (a, b, c, d, s) или null, если решения нет до границы.</returns>
    private static (int a, int b, int c, int d, int s)? FindSmallestSolution(int limit)
    {
        for (int s = MinSum; s <= limit; s++)
        {
            var pairs = PairsWithSquareSum(s);

            if (pairs.Count >= 2)
                return (pairs[0].x, pairs[0].y, pairs[1].x, pairs[1].y, s);
        }

        return null;
    }

    /// <summary>
    /// Собирает все пары (x, y), где y > x и x^2 + y^2 = s.
    /// Условие y > x гарантирует x != y и что каждая пара попадет
    /// в список только один раз.
    /// </summary>
    private static List<(int x, int y)> PairsWithSquareSum(int s)
    {
        var pairs = new List<(int x, int y)>();

        // 2 * x * x < s: при y = x сумма уже равна s, значит больший x не нужен
        for (int x = 1; 2 * x * x < s; x++)
        {
            int y = (int)Math.Sqrt(s - x * x); // кандидат: y^2 = s - x^2

            // повторная проверка отсекает погрешность округления Sqrt (точность)
            if (y > x && x * x + y * y == s)
                pairs.Add((x, y));
        }

        return pairs;
    }

    /// <summary>
    /// Самопроверка решения перед выводом: уравнение выполнено,
    /// пары различны (надежность, точность).
    /// </summary>
    private static bool IsValid((int a, int b, int c, int d, int s) solution)
    {
        var (a, b, c, d, s) = solution;

        return a != b && c != d
            && a * a + b * b == s
            && c * c + d * d == s;
    }

    /// <summary>Печатает найденное решение, предварительно проверив его.</summary>
    private static void PrintSolution((int a, int b, int c, int d, int s) solution)
    {
        if (!IsValid(solution))
        {
            Console.WriteLine("Внутренняя ошибка: решение не прошло самопроверку.");
            return;
        }

        var (a, b, c, d, s) = solution;

        Console.WriteLine();
        Console.WriteLine("Наименьшее натуральное решение уравнения a^2 + b^2 = c^2 + d^2:");
        Console.WriteLine($"{a}^2 + {b}^2 = {c}^2 + {d}^2 = {s}");
    }
}
